// Assemble reviewed source ranges at native speed, followed by a one-second paper end card.
const fs=require('node:fs'),path=require('node:path'),{spawnSync}=require('node:child_process');
const {createCanvas}=require('@napi-rs/canvas');
const root=path.resolve(__dirname,'..'),out=path.join(root,'Video/research/v3');
fs.mkdirSync(path.join(root,'.video-work/v3frames'),{recursive:true});
const plan=JSON.parse(fs.readFileSync(path.join(out,'edit-plan.json'),'utf8').replace(/^\uFEFF/,''));
const ffmpeg=process.env.FFMPEG_PATH||path.join(root,'.video-work/tools/imageio_ffmpeg/binaries/ffmpeg-win-x86_64-v7.1.exe');
if(!plan.review.actualClipsReviewed)throw Error('Review the actual video clips before assembling the final film.');
const inputs=plan.clips.map(clip=>{
 const file=path.join(out,clip.file);
 if(!fs.existsSync(file))throw Error(`Missing actual video: ${clip.file}`);
 if(!Number.isFinite(clip.sourceStart)||!Number.isFinite(clip.sourceDuration)||!Number.isFinite(clip.useDuration)||clip.sourceDuration+0.02<clip.sourceStart+clip.useDuration)throw Error(`Unverified source range: ${clip.file}`);
 return file;
});
if(plan.clips.reduce((sum,clip)=>sum+clip.useDuration,0)!==29)throw Error('Expected 29 seconds of unique moving footage plus the one-second paper card.');
const card=createCanvas(416,720),ctx=card.getContext('2d');
ctx.fillStyle='#172226';ctx.fillRect(0,0,416,720);
ctx.fillStyle='#eddbb0';ctx.fillRect(34,165,40,3);
ctx.font='bold 16px Arial';ctx.fillText('PPEL+ RESEARCH SHORT',34,210);
ctx.fillStyle='#fffaf0';ctx.font='bold 35px Arial';
ctx.fillText('From petals',34,290);ctx.fillText('to signals.',34,335);
ctx.font='22px Arial';ctx.fillStyle='#dbcdd0';ctx.fillText('Nano Energy · 2026',34,400);
ctx.font='15px Arial';ctx.fillText('10.1016/j.nanoen.2025.111687',34,435);
ctx.fillStyle='#eddbb0';ctx.font='bold 18px Arial';ctx.fillText('READ THE PAPER  →',34,525);
const cardPath=path.join(out,'cherry-action-paper-card.png');fs.writeFileSync(cardPath,card.toBuffer('image/png'));
const endCard=createCanvas(1280,720),ec=endCard.getContext('2d');
ec.fillStyle='#172226';ec.fillRect(0,0,1280,720);
ec.fillStyle='#eddbb0';ec.font='bold 28px Arial';ec.fillText('PPEL+',100,175);
ec.fillStyle='#fffaf0';ec.font='bold 68px Arial';ec.fillText('From petals to signals.',100,305);
ec.fillStyle='#dbcdd0';ec.font='28px Arial';ec.fillText('Nano Energy · 2026',100,393);
ec.font='24px Arial';ec.fillText('10.1016/j.nanoen.2025.111687',100,438);
ec.fillStyle='#eddbb0';ec.font='bold 24px Arial';ec.fillText('READ THE PAPER  →',100,550);
const endCardPath=path.join(out,'cherry-action-end-card.png');fs.writeFileSync(endCardPath,endCard.toBuffer('image/png'));
const normalize='fps=24,scale=1280:720:force_original_aspect_ratio=decrease,pad=1280:720:(ow-iw)/2:(oh-ih)/2,setsar=1';
const filters=[];
const loudness=[];
plan.clips.forEach((clip,i)=>{
 const measured=spawnSync(ffmpeg,['-hide_banner','-ss',String(clip.sourceStart),'-t',String(clip.useDuration),'-i',inputs[i],'-vn','-af','loudnorm=I=-16:TP=-1.5:LRA=11:print_format=json','-f','null','-'],{encoding:'utf8'});
 if(measured.status)throw Error(`Audio analysis failed: ${clip.file}`);
 const stats=JSON.parse(measured.stderr.match(/\{\s*"input_i"[\s\S]*?\}/)?.[0]||'null');
 if(!stats||!Number.isFinite(Number(stats.input_i)))throw Error(`Missing loudness data: ${clip.file}`);
 loudness.push({file:clip.file,...stats});
 const audioNormalize=`loudnorm=I=-16:TP=-1.5:LRA=11:measured_I=${stats.input_i}:measured_TP=${stats.input_tp}:measured_LRA=${stats.input_lra}:measured_thresh=${stats.input_thresh}:offset=${stats.target_offset}:linear=true`;
 filters.push(`[${i}:v]trim=start=${clip.sourceStart}:duration=${clip.useDuration},setpts=PTS-STARTPTS,${normalize}[v${i}]`);
 filters.push(`[${i}:a]atrim=start=${clip.sourceStart}:duration=${clip.useDuration},asetpts=PTS-STARTPTS,${audioNormalize},aresample=48000,aformat=channel_layouts=stereo[a${i}]`);
});
fs.writeFileSync(path.join(root,'.video-work/v3frames/loudness-normalization.json'),JSON.stringify(loudness,null,2)+'\n');
filters.push('[v0][a0][v1][a1][v2][a2]concat=n=3:v=1:a=1[full][sound]');
filters.push('[sound]afade=t=out:st=28.65:d=0.35,apad=whole_dur=30[a]');
filters.push('[full]split[body][tail]');
filters.push('[body]trim=end=28,setpts=PTS-STARTPTS[body28]');
// The final moving picture is resized beside the paper card; the card covers no action.
filters.push('[tail]trim=start=28:end=29,setpts=PTS-STARTPTS,scale=864:486,pad=1280:720:0:117:color=0x172226[tail1]');
filters.push('[tail1][3:v]overlay=x=864:y=0:shortest=1[outro]');
filters.push('[4:v]trim=duration=1,setpts=PTS-STARTPTS,setsar=1[endcard]');
filters.push('[body28][outro][endcard]concat=n=3:v=1:a=0,setpts=N/(24*TB)[v]');
const movie=path.join(out,'cherry-action-30s.mp4');
const args=['-hide_banner','-loglevel','error','-y',...inputs.flatMap(file=>['-i',file]),... [cardPath,endCardPath].flatMap(file=>['-loop','1','-framerate','24','-i',file]),'-filter_complex',filters.join(';'),'-map','[v]','-map','[a]','-t','30','-r','24','-fps_mode','cfr','-c:v','libx264','-crf','20','-preset','medium','-pix_fmt','yuv420p','-c:a','aac','-b:a','128k','-movflags','+faststart',movie];
let result=spawnSync(ffmpeg,args,{stdio:'inherit'});if(result.status)process.exit(result.status);
result=spawnSync(ffmpeg,['-hide_banner','-loglevel','error','-y','-ss','2.3','-i',movie,'-frames:v','1',path.join(out,'cherry-action-30s.jpg')],{stdio:'inherit'});if(result.status)process.exit(result.status);
const stamp=t=>`00:00:${t.toFixed(3).padStart(6,'0')}`;
for(const language of ['ko','en'])fs.writeFileSync(path.join(out,`cherry-action-30s.${language}.vtt`),'WEBVTT\n\n'+plan.captions.cues.map((cue,index)=>`${index+1}\n${stamp(cue.start)} --> ${stamp(cue.end)}\n${cue[language]}\n`).join('\n'));
console.log(`29 seconds of unique animation + 1-second paper card: ${movie}`);
