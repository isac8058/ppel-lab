// Assemble the reviewed two-scene anime edit; never loop a scene to fill time.
// Original scene action occupies 23 seconds, followed by a 5-second closing
// reaction hold for the science caption and a 2-second exact paper card.
const fs=require('node:fs'),path=require('node:path'),{spawnSync}=require('node:child_process');
const root=path.resolve(__dirname,'..'),out=path.join(root,'Video/research/v2');
const ffmpeg=process.env.FFMPEG_PATH||path.join(root,'.video-work/tools/imageio_ffmpeg/binaries/ffmpeg-win-x86_64-v7.1.exe');
const input=['cherry-pilot.mp4','cherry-lab.mp4','cherry-blossom-endcard.png'].map(file=>path.join(out,file));
input.forEach(file=>{if(!fs.existsSync(file))throw new Error(`Missing reviewed scene: ${file}`);});
const video='scale=1280:720:force_original_aspect_ratio=decrease,pad=1280:720:(ow-iw)/2:(oh-ih)/2,setsar=1';
const graph=[
 `[0:v]trim=duration=10,setpts=1.15*(PTS-STARTPTS),fps=24,${video},trim=duration=11.5[v0]`,
 '[0:a]atrim=duration=10,asetpts=PTS-STARTPTS,atempo=0.8695652174,apad,atrim=duration=11.5,aformat=sample_rates=48000:channel_layouts=stereo[a0]',
 // Gemini returned a 20-second continuation containing the first scene again.
 // Use only its new laboratory segment so the opening never repeats.
 `[1:v]trim=start=10:duration=10,setpts=1.15*(PTS-STARTPTS),fps=24,${video},trim=duration=11.5,tpad=stop_mode=clone:stop_duration=5[v1]`,
 '[1:a]atrim=start=10:duration=10,asetpts=PTS-STARTPTS,atempo=0.8695652174,apad,atrim=duration=16.5,aformat=sample_rates=48000:channel_layouts=stereo[a1]',
 `[2:v]${video},fps=24,trim=duration=2,setpts=PTS-STARTPTS[v2]`,
 'anullsrc=r=48000:cl=stereo,atrim=duration=2[a2]',
 '[v0][a0][v1][a1][v2][a2]concat=n=3:v=1:a=1[joined][a]',
 '[joined]setpts=N/(24*TB)[v]'
].join(';');
const movie=path.join(out,'cherry-blossom-30s.mp4');
const args=['-hide_banner','-loglevel','error','-y','-i',input[0],'-i',input[1],'-loop','1','-i',input[2],'-filter_complex',graph,'-map','[v]','-map','[a]','-t','30','-r','24','-fps_mode','cfr','-c:v','libx264','-preset','medium','-crf','20','-pix_fmt','yuv420p','-c:a','aac','-b:a','128k','-movflags','+faststart',movie];
let result=spawnSync(ffmpeg,args,{stdio:'inherit'});if(result.status)process.exit(result.status);
result=spawnSync(ffmpeg,['-hide_banner','-loglevel','error','-y','-i',movie,'-frames:v','1',path.join(out,'cherry-blossom-30s.jpg')],{stdio:'inherit'});if(result.status)process.exit(result.status);
const cues=[
 [0,3,'The most romantic scene. Almost.','가장 로맨틱한 순간. 거의.'],
 [7,11.5,'Great harvest today!','오늘 수율 좋다!'],
 [11.5,15,'Petals inside. A tap outside.','꽃잎을 넣은 소자에 톡, 톡.'],
 [18,23,"It knows. It's a double tap.",'구분했어… 두 번인 걸…'],
 [23,28,'Machine learning distinguishes single and double taps from signals generated by a fabricated cherry-petal sensor.','벚꽃잎 소자의 단일·이중 탭 신호를 머신러닝으로 구별합니다.'],
 [28,30,'Read the paper · PPEL+','논문 보기 · PPEL+']
];
const stamp=t=>`00:00:${t.toFixed(3).padStart(6,'0')}`;
for(const [language,column] of [['en',2],['ko',3]]){
 fs.writeFileSync(path.join(out,`cherry-blossom-30s.${language}.vtt`),'WEBVTT\n\n'+cues.map((cue,index)=>`${index+1}\n${stamp(cue[0])} --> ${stamp(cue[1])}\n${cue[column]}\n`).join('\n'));
}
console.log(`Thirty-second anime edit and below-picture caption tracks: ${movie}`);
